const path = require('node:path')
const fs = require('node:fs')
const { _electron: electron } = require('playwright-core')

async function main() {
  const project = path.resolve(__dirname, '..')
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: project })
  const page = await app.firstWindow()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.waitForSelector('.app-shell.ready', { timeout: 20000 })
  await page.evaluate(() => { localStorage.clear(); indexedDB.deleteDatabase('framemark') })
  await page.reload()
  await page.waitForSelector('.app-shell.ready', { timeout: 20000 })
  await page.waitForTimeout(1000)
  await page.setInputFiles('#framemark-file-input', 'D:/border&watermark/_research/test-assets/p1170883.jpg')
  await page.waitForSelector('.thumb', { timeout: 120000 })
  await page.waitForTimeout(2200)
  await page.locator('.inspector-tabs button', { hasText: '水印' }).click()
  await page.waitForTimeout(300)
  await page.setInputFiles('input[type=file][accept="image/png,image/webp,image/jpeg"]', 'D:/border&watermark/_research/test-assets/wm-black.png')
  await page.waitForTimeout(1000)
  await page.locator('.topbar-actions .icon-btn[title="保存预设 / 导入导出"]').click()
  await page.waitForSelector('.modal')
  await page.locator('.preset-save-box input').fill('水印边框验收预设')
  await page.locator('.preset-save-box button', { hasText: '保存当前设计' }).click()
  await page.waitForTimeout(1200)
  console.log('saved presets', await page.locator('.preset-row').count())
  await page.locator('.topbar-actions .icon-btn[title="保存预设 / 导入导出"]').click()
  await page.waitForSelector('.modal')
  await page.locator('.preset-foot button', { hasText: '导出预设' }).click()
  let exportedToast = ''
  for (let i = 0; i < 20; i++) {
    await page.waitForTimeout(300)
    exportedToast = await page.locator('.toast').innerText().catch(() => '')
    if (exportedToast.includes('预设已保存到')) break
  }
  console.log('export toast', exportedToast)
  const downloadDir = 'D:/下载/FrameMark'
  const files = fs.readdirSync(downloadDir).filter((f) => f.endsWith('.json')).sort().reverse()
  console.log('export files', files.slice(0, 3))
  const jsonPath = path.join(downloadDir, files[0])
  const parsed = JSON.parse(fs.readFileSync(jsonPath, 'utf8'))
  console.log('json presets', parsed.presets?.length, 'wm', Boolean(parsed.currentDesign?.watermark?.asset))
  await page.locator('.modal-foot button', { hasText: '完成' }).click()
  await page.waitForTimeout(300)
  await page.locator('.topbar-actions .icon-btn[title="保存预设 / 导入导出"]').click()
  await page.waitForSelector('.modal')
  await page.locator('.preset-row .icon-btn.danger').click()
  await page.waitForTimeout(700)
  console.log('after delete', await page.locator('.preset-row').count())
  await page.setInputFiles('.preset-foot input[type=file]', jsonPath)
  await page.waitForTimeout(1200)
  console.log('after import toast', await page.locator('.toast').innerText().catch(() => ''))
  console.log('after import presets', await page.locator('.preset-row').count())
  await page.locator('.preset-row button', { hasText: '应用' }).click()
  await page.waitForTimeout(1800)
  console.log('applied template', (await page.locator('.stage-title').innerText()).replace(/\n+/g, ' | '))
  await page.locator('.inspector-tabs button', { hasText: '水印' }).click()
  await page.waitForTimeout(500)
  console.log('applied wm', (await page.locator('.wm-info').innerText()).replace(/\n+/g, ' | '))
  console.log('errors', errors)
  await app.close()
}
main().catch((e) => { console.error(e); process.exit(1) })
