// Apply a user-exported logo selection to the app catalog.
// Usage: node scripts/logo-pipeline/apply-selection.mjs [selection.json]
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const APP = 'D:/border&watermark/framemark'
const CATALOG = path.join(APP, 'src/renderer/src/core/logo-catalog.ts')
const DEFAULT_SELECTION = 'D:/border&watermark/framemark-logo-selection-20261027.json'
const SELECTION = process.argv[2] || DEFAULT_SELECTION
const OUT_TS = path.join(APP, 'src/renderer/src/core/logo-selection.generated.ts')
const AUDIT = 'D:/border&watermark/_research/logo-versions/_audit'

const MAP = { lumix: 'panasionic', lumo: 'oppo' }
const HIDDEN = ['lumix', 'lumo']

const result = await build({ entryPoints: [CATALOG], bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'silent' })
const tmp = path.join(os.tmpdir(), `framemark-selection-${process.pid}.mjs`)
fs.writeFileSync(tmp, result.outputFiles[0].text)
const mod = await import(pathToFileURL(tmp).href)
fs.rmSync(tmp, { force: true })

const selection = JSON.parse(fs.readFileSync(SELECTION, 'utf8'))
const selectedRows = Array.isArray(selection.selected) ? selection.selected : []
const selectedIds = [...new Set(selectedRows.map((r) => r.versionId).filter(Boolean))]
const allIds = new Set(mod.LOGO_VERSIONS.map((v) => v.id))
const missing = selectedIds.filter((id) => !allIds.has(id))
if (missing.length) {
  console.error('selected ids missing from catalog:', missing)
  process.exit(2)
}
const selectedSet = new Set(selectedIds)
const unselected = mod.LOGO_VERSIONS.filter((v) => !selectedSet.has(v.id))

// Display groups: LUMIX -> Panasonic, LUMO -> OPPO; hidden source brands are not standalone.
const brandByKey = new Map(mod.LOGO_BRANDS.map((b) => [b.key, b]))
const groups = new Map()
for (const v of mod.LOGO_VERSIONS) {
  if (!selectedSet.has(v.id)) continue
  const displayKey = MAP[v.brandKey] ?? v.brandKey
  if (HIDDEN.includes(displayKey) && !MAP[displayKey]) continue
  const meta = brandByKey.get(displayKey) ?? brandByKey.get(v.brandKey)
  if (!groups.has(displayKey)) {
    groups.set(displayKey, { key: displayKey, label: meta?.label ?? displayKey, cn: meta?.cn ?? '', group: meta?.group ?? 'camera', versions: [] })
  }
  groups.get(displayKey).versions.push(v)
}
const displayGroups = [...groups.values()].sort((a, b) => {
  const ai = mod.LOGO_BRANDS.findIndex((x) => x.key === a.key)
  const bi = mod.LOGO_BRANDS.findIndex((x) => x.key === b.key)
  return ai - bi
})

const byBrand = {}
for (const v of unselected) {
  byBrand[v.brandKey] = byBrand[v.brandKey] || []
  byBrand[v.brandKey].push(v.id)
}
for (const k of Object.keys(byBrand)) byBrand[k].sort()

const ts = `// AUTO-GENERATED by scripts/logo-pipeline/apply-selection.mjs
// Source: ${path.basename(SELECTION)} (${selection.exportedAt ?? 'unknown'})
// ${selectedIds.length}/${mod.LOGO_VERSIONS.length} versions selected by the user.
export const SELECTED_LOGO_VERSION_IDS: string[] = ${JSON.stringify(selectedIds, null, 2)}
export const SELECTED_LOGO_VERSION_ID_SET = new Set<string>(SELECTED_LOGO_VERSION_IDS)
export const SELECTED_LOGO_VERSION_COUNT = ${selectedIds.length}
export const ALL_LOGO_VERSION_COUNT = ${mod.LOGO_VERSIONS.length}
export const LOGO_DISPLAY_BRAND_MAP: Record<string, string> = ${JSON.stringify(MAP, null, 2)}
export const LOGO_HIDDEN_DISPLAY_BRANDS: string[] = ${JSON.stringify(HIDDEN)}
export const DISPLAY_LOGO_BRAND_COUNT = ${displayGroups.length}
export function isLogoVersionSelected (id: string): boolean {
  return SELECTED_LOGO_VERSION_ID_SET.has(id)
}
export function displayBrandKeyFor (brandKey: string): string {
  return LOGO_DISPLAY_BRAND_MAP[brandKey] ?? brandKey
}
`
fs.writeFileSync(OUT_TS, ts)

const summary = {
  source: SELECTION,
  exportedAt: selection.exportedAt,
  selected: selectedIds.length,
  unselected: unselected.length,
  displayBrandCount: displayGroups.length,
  brandMap: MAP,
  hiddenBrands: HIDDEN,
  unselectedByBrand: byBrand,
  displayGroups: displayGroups.map((g) => ({ key: g.key, label: g.label, cn: g.cn, versions: g.versions.map((v) => v.id) }))
}
fs.mkdirSync(AUDIT, { recursive: true })
fs.writeFileSync(path.join(AUDIT, 'SELECTION-APPLIED.json'), JSON.stringify(summary, null, 2))
const lines = [
  '# Logo selection applied',
  '',
  `- source: \`${path.basename(SELECTION)}\` (${selection.exportedAt ?? 'unknown'})`,
  `- selected: **${selectedIds.length}** / ${mod.LOGO_VERSIONS.length}`,
  `- unselected (hidden from app picker, sources kept): **${unselected.length}**`,
  `- display brands: **${displayGroups.length}** (LUMIX → Panasonic, LUMO → OPPO)`,
  '',
  '## Unselected',
  '',
  ...Object.entries(byBrand).map(([k, ids]) => `- **${k}** (${ids.length}): ${ids.join(', ')}`),
  '',
  '## Display groups',
  '',
  ...displayGroups.map((g) => `- **${g.label} · ${g.cn}** (${g.versions.length}): ${g.versions.map((v) => v.id).join(', ')}`)
]
fs.writeFileSync(path.join(AUDIT, 'SELECTION-APPLIED.md'), lines.join('\n'))
console.log(JSON.stringify({ selected: selectedIds.length, unselected: unselected.length, displayBrands: displayGroups.length, out: OUT_TS, audit: path.join(AUDIT, 'SELECTION-APPLIED.md') }, null, 2))
